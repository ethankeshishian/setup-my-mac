#!/usr/bin/env bash

smm_etc_entries() {
  local repo host ref state
  repo=$(smm_repo) && host=$(smm_host) || return 1
  state=$(smm_state_dir) || return 1
  if [ "${SMM_PLAN:-0}" != 1 ] && [ -f "$state/last-build-flake" ]; then
    ref=$(cat "$state/last-build-flake") || return 1
  else
    # The snapshot includes generated/untracked host modules but never ignored
    # files. A path: flake of the checkout would copy secrets into the store.
    ref=$(SMM_AGENT_SETUP=1 smm_flake_ref) || return 1
  fi
  # shellcheck disable=SC2016 # Nix lambda, not shell interpolation.
  smm_nix eval --no-write-lock-file --json "$ref#darwinConfigurations.$host.config.environment.etc" --apply '
    entries: builtins.mapAttrs (name: entry: {
      inherit (entry) target knownSha256Hashes enable;
    }) (builtins.removeAttrs entries (builtins.filter
      (name: !entries.${name}.enable) (builtins.attrNames entries)))'
}
smm_etc_classify() {
  local root stock
  root=$(smm_resource_root) || return 1
  stock="$root/data/etc-stock/$2"
  [ -f "$stock" ] || stock=/dev/null
  jq -Rs --rawfile stock "$stock" -f "$root/data/etc-classify.jq" "$1"
}
smm_nix_string() {
  # JSON strings share Nix's escapes for this text, except Nix interpolation.
  jq -Rn --arg s "$1" '$s | tojson | gsub("\\$\\{"; "\\${")' -r
}
smm_etc_pending() {
  local entries name entry target file sha known generated root resolved_root resolved_static link_dest
  entries=$(smm_etc_entries) || return "$?"
  jq -e 'type == "object"' <<< "$entries" >/dev/null || return 1
  root=${SMM_ETC_ROOT:-/etc}
  resolved_root=$(cd -P "$root" && pwd) || return 1
  generated="$(smm_repo)/hosts/etc/$(smm_host).nix"
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    entry=$(jq -c --arg name "$name" '.[$name]' <<< "$entries") || return 1
    [ "$(jq -r '.enable' <<< "$entry")" = true ] || continue
    target=$(jq -er '.target' <<< "$entry") || return 1
    smm_safe_relative "$target" || { warn "unsafe etc target: $target"; return 1; }
    file="$root/$target"
    [ -f "$file" ] || continue
    if [ -L "$file" ]; then
      link_dest=$(readlink "$file") || return 1
      case "$link_dest" in /etc/static/*|"$root/static/"*|static/*) continue ;; esac
      resolved_static=$(readlink -f "$root/static") || resolved_static="$resolved_root/static"
      case "$(readlink -f "$file")" in "$root/static/"*|"$resolved_root/static/"*|"$resolved_static/"*|/etc/static/*) continue ;; esac
      warn "inspect unmanaged /etc symlink: $file"; return 1
    fi
    sha=$(shasum -a 256 "$file" | awk '{print $1}') || return 1
    known=$(jq -r --arg sha "$sha" '.knownSha256Hashes | index($sha)' <<< "$entry") || return 1
    [ "$known" = null ] || continue
    # Only skip the exact entry/hash pair already accepted in our generated file.
    if [ -f "$generated" ] && grep -Fxq "    # smm-accepted $(smm_nix_string "$name") $sha" "$generated"; then continue; fi
    jq -cn --arg name "$name" --arg target "$target" --arg sha "$sha" \
      '{name:$name,target:$target,sha:$sha}' || return 1
  done < <(jq -r 'keys[]' <<< "$entries")
}
step_etc_done() {
  local pending
  pending=$(smm_etc_pending) || return "$?"
  [ -z "$pending" ]
}
step_etc_run() (
  pending=$(smm_etc_pending) || exit "$?"
  [ -n "$pending" ] || exit 0
  host=$(smm_host) && repo=$(smm_repo) || exit 1
  case "$host" in ''|-*|*[!a-zA-Z0-9-]*) warn 'invalid host name'; exit 1 ;; esac
  tmp=$(mktemp -d) || exit 1
  module_tmp=''
  trap 'rm -rf "$tmp"; [ -z "$module_tmp" ] || rm -f "$module_tmp"' EXIT
  file="$repo/hosts/etc/$host.nix"
  # Prepare all changes and all confirmations before replacing the module.
  if [ -f "$file" ]; then cp "$file" "$tmp/module"; else
    printf '# Generated by smm setup on %s.\n{ lib, ... }: {\n  imports = [\n  ];\n}\n' "$(date +%F)" > "$tmp/module"
  fi
  while IFS= read -r entry; do
    name=$(jq -r .name <<< "$entry"); target=$(jq -r .target <<< "$entry"); sha=$(jq -r .sha <<< "$entry")
    classification=$(smm_etc_classify "${SMM_ETC_ROOT:-/etc}/$target" "$target") || exit 1
    log "/etc/$target: exact keep/drop review (uncertain macOS stock lines are kept):"
    jq -r '.review[] | "\(.action) [\(.reason)] \(.line)"' <<< "$classification"
    answer=$(smm_answer "etc.$name" "Accept the keep/drop review for /etc/$target?" accept stop) || exit "$?"
    [ "$answer" = accept ] || { warn "Review /etc/$target, then rerun smm setup; no /etc files were changed."; exit 1; }
    [ "$sha" = "$(shasum -a 256 "${SMM_ETC_ROOT:-/etc}/$target" | awk '{print $1}')" ] || { warn '/etc changed during review; rerun setup'; exit 1; }
    shell=$(jq -r '.shell' <<< "$classification")
    option=''
    case "$target" in zshenv) option=programs.zsh.shellInit ;; zshrc) option=programs.zsh.interactiveShellInit ;; bashrc) option=programs.bash.interactiveShellInit ;; esac
    if [ -n "$shell" ] && [ -z "$option" ]; then warn "No shell-init option for /etc/$target. Preserve it in a host module and rerun setup."; exit 1; fi
    quoted=$(smm_nix_string "$name")
    {
      printf '    # smm-entry %s\n    {\n' "$quoted"
      printf '    # smm-accepted %s %s\n' "$quoted" "$sha"
      printf '      # Kept literal exports and shell code; dropped installer/stock lines after review.\n'
      printf '      environment.etc.%s.knownSha256Hashes = lib.mkAfter [ "%s" ];\n' "$quoted" "$sha"
      while IFS= read -r variable; do
        [ -n "$variable" ] || continue
        value=$(jq -r --arg key "$variable" '.variables[$key]' <<< "$classification")
        printf '      environment.variables.%s = %s;\n' "$(smm_nix_string "$variable")" "$(smm_nix_string "$value")"
      done < <(jq -r '.variables | keys[]' <<< "$classification")
      [ -z "$shell" ] || printf '      %s = lib.mkAfter %s;\n' "$option" "$(smm_nix_string "$shell"$'\n')"
      printf '    }\n    # smm-end %s\n' "$quoted"
    } > "$tmp/block"
    # Keep other accepted entries, replacing this entry atomically.
    awk -v start="    # smm-entry $quoted" -v end="    # smm-end $quoted" '
      $0 == start {skip=1} !skip {print} $0 == end {skip=0}
    ' "$tmp/module" > "$tmp/old"
    awk -v block="$tmp/block" '
      /^  \];$/ {while ((getline line < block)>0) print line; close(block)} {print}
    ' "$tmp/old" > "$tmp/module"
  done <<< "$pending"
  mkdir -p "$repo/hosts/etc" || exit 1
  # Accepted takeover declarations survive pauses; the original /etc files never move.
  module_tmp=$(mktemp "$repo/hosts/etc/.module.XXXXXX") || exit 1
  { printf '# Generated by smm setup on %s.\n' "$(date +%F)"; sed '1d' "$tmp/module"; } > "$module_tmp" || exit 1
  mv "$module_tmp" "$file" || exit 1
  module_tmp=''
  step_build_run
)

smm_etc_accepted_report() {
  local names host generated
  host=$(smm_host) || return 1
  generated="$(smm_repo)/hosts/etc/$host.nix"
  [ -f "$generated" ] || return 0
  # The accepted original hashes remain useful after activation changes the
  # content and replaces files with /etc/static symlinks. Report the saved names.
  names=$(sed -n 's/^    # smm-accepted \(.*\) [0-9a-f]\{64\}$/\1/p' "$generated" | jq -sr 'unique | join(" ")') || return 1
  [ -n "$names" ] || return 0
  log "already accepted in hosts/etc/$host.nix: $names"
}
# Read-only: says per file whether a decision is pending, already accepted, or
# moot because nix-darwin replaces the whole file.
smm_etc_review() (
  tmp=$(mktemp -d) || exit 1
  trap 'rm -rf "$tmp"' EXIT
  export SMM_STATE="$tmp/state" SMM_PLAN=1 SMM_AGENT_SETUP=0
  generated="$(smm_repo)/hosts/etc/$(smm_host).nix" || exit 1
  entries=$(smm_etc_entries) || exit 1
  jq -e 'type == "object"' <<< "$entries" >/dev/null || exit 1
  names=$(jq -r 'keys[]' <<< "$entries") || exit 1
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    entry=$(jq -c --arg name "$name" '.[$name]' <<< "$entries") || exit 1
    [ "$(jq -r .enable <<< "$entry")" = true ] || continue
    target=$(jq -er .target <<< "$entry") || exit 1
    smm_safe_relative "$target" || { warn "unsafe etc target: $target"; exit 1; }
    file="${SMM_ETC_ROOT:-/etc}/$target"
    [ -f "$file" ] || continue
    if [ -L "$file" ]; then
      case "$(readlink -f "$file")" in
        */static/*|/nix/store/*) log "/etc/$target: managed by nix-darwin already; nothing to review"; continue ;;
      esac
    fi
    sha=$(shasum -a 256 "$file" | awk '{print $1}') || exit 1
    # Accepted entries add their hash to knownSha256Hashes too, so check the
    # accepted marker first; otherwise they would be reported as stock.
    if [ -f "$generated" ] && grep -Fxq "    # smm-accepted $(smm_nix_string "$name") $sha" "$generated"; then
      status="already accepted in hosts/etc/$(basename "$generated")"
    elif [ "$(jq -r --arg sha "$sha" '.knownSha256Hashes | index($sha)' <<< "$entry")" != null ]; then
      log "/etc/$target: known stock hash: replaced entirely by nix-darwin; nothing in it is kept"
      continue
    else
      status='pending (decision needed)'
    fi
    classification=$(smm_etc_classify "$file" "$target") || exit 1
    log "/etc/$target: $status. Exact keep/drop review:"
    jq -r '.review[] | "\(.action) [\(.reason)] \(.line)"' <<< "$classification" || exit 1
  done <<< "$names"
)
